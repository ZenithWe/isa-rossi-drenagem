create extension if not exists btree_gist;
create table if not exists public.isa_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.isa_services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  duration_minutes int not null check (duration_minutes between 15 and 240 and duration_minutes % 15 = 0),
  price numeric(10,2) check (price >= 0),
  active boolean not null default true
);
create table if not exists public.isa_working_hours (
  weekday int primary key check(weekday between 0 and 6),
  start_time time not null,
  end_time time not null,
  active boolean not null default true,
  check(end_time > start_time)
);
create table if not exists public.isa_appointments (
  id uuid primary key default gen_random_uuid(),
  service_id bigint not null references public.isa_services(id),
  customer_name text not null check(length(customer_name) between 2 and 120),
  phone text not null check(length(phone) between 8 and 25),
  email text,
  notes text,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'pending' check(status in ('pending','confirmed','completed','cancelled','no_show')),
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
