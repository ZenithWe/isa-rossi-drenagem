-- RPC retorna apenas horários, nunca nome, telefone ou qualquer dado das clientes.
create or replace function public.isa_available_slots(p_service_id bigint,p_date date)
returns table(slot_time text) language plpgsql security definer set search_path='' as $$
declare svc public.isa_services%rowtype; hrs public.isa_working_hours%rowtype; t time; a timestamptz; b timestamptz;
begin
  if p_date < (now() at time zone 'America/Sao_Paulo')::date or p_date > (now() at time zone 'America/Sao_Paulo')::date + 90 then return; end if;
  select * into svc from public.isa_services where id=p_service_id and active;
  if not found then return; end if;
  select * into hrs from public.isa_working_hours where weekday=extract(dow from p_date)::int and active;
  if not found then return; end if;
  t:=hrs.start_time;
  while t + make_interval(mins=>svc.duration_minutes) <= hrs.end_time loop
    a:=(p_date::text || ' ' || t::text)::timestamp at time zone 'America/Sao_Paulo';
    b:=a+make_interval(mins=>svc.duration_minutes);
    if a>now() and not exists(select 1 from public.isa_appointments x where x.status in ('pending','confirmed','completed') and tstzrange(x.starts_at,x.ends_at,'[)') && tstzrange(a,b,'[)')) then
      slot_time:=to_char(t,'HH24:MI'); return next;
    end if;
    t:=t+interval '30 minutes';
  end loop;
end $$;
revoke all on function public.isa_available_slots(bigint,date) from public;
grant execute on function public.isa_available_slots(bigint,date) to anon,authenticated;
-- Reservas são criadas por RPC, com horário validado no banco.
create or replace function public.isa_book(p_service_id bigint,p_date date,p_time text,p_name text,p_phone text,p_email text default null,p_notes text default null)
returns uuid language plpgsql security definer set search_path='' as $$
declare s public.isa_services%rowtype; start_at timestamptz; appointment_id uuid;
begin
 if length(trim(p_name)) not between 2 and 120 or length(trim(p_phone)) not between 8 and 25 or length(coalesce(p_notes,''))>1000
 then raise exception 'Dados inválidos'; end if;
 if not exists(select 1 from public.isa_available_slots(p_service_id,p_date) v where v.slot_time=p_time) then raise exception 'Horário indisponível'; end if;
 select * into s from public.isa_services where id=p_service_id and active;
 start_at:=(p_date::text || ' ' || p_time)::timestamp at time zone 'America/Sao_Paulo';
 insert into public.isa_appointments(service_id,customer_name,phone,email,notes,starts_at,ends_at)
 values(p_service_id,trim(p_name),trim(p_phone),nullif(trim(coalesce(p_email,'')),''),nullif(trim(coalesce(p_notes,'')),''),start_at,start_at+make_interval(mins=>s.duration_minutes))
 returning id into appointment_id;
 return appointment_id;
exception when exclusion_violation then raise exception 'Esse horário acabou de ser reservado';
end $$;
revoke all on function public.isa_book(bigint,date,text,text,text,text,text) from public;
grant execute on function public.isa_book(bigint,date,text,text,text,text,text) to anon,authenticated;
